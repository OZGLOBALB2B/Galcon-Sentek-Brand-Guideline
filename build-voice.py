#!/usr/bin/env python3
"""Rebuild the Verbal Language chapter of index.html from brand-story.json.
Usage: python3 build-voice.py   (run inside this folder)"""
import json, html, re
d = json.load(open('brand-story.json', encoding='utf-8'))
e = html.escape
S, V = d['strategy'], d['verbal']
A, B = S['balance']['poles']
auds = V['audiences']
pole = {p['id']: p for p in (A, B)}

def polecard(p, cls):
    return f'''<div class="pole {cls}"><p class="role">{e(p['subtitle'])}</p><h4>{e(p['name'])}</h4>
<p class="insight">{e(p['insight'])}</p><p class="desc">{e(p['description'])}</p></div>'''

def attr(a):
    cls = 'pa' if a['pole'] == A['id'] else 'pb'
    ex = ''.join(
        f'<div class="ex" data-aud="{e(u["id"])}"><p class="exl">Examples for the {e(u["name"]).lower()}</p>'
        + (''.join(f'<blockquote>{e(l)}</blockquote>' for l in a['examples'].get(u['id'], [])) or '<p class="note">No examples yet.</p>')
        + '</div>' for u in auds)
    say = ''.join(f'<li>{e(x)}</li>' for x in a['doSay'])
    dont = ''.join(f'<li>{e(x)}</li>' for x in a['dontSay'])
    kw = ''.join(f'<span>{e(k)}</span>' for k in a['toneKeywords'])
    return f'''<article class="attr {cls}">
<div class="attr-head"><h4>{e(a['name'])}</h4><span class="leans">Leans to {e(pole[a['pole']]['name'])}</span></div>
<div class="attr-body"><div><p class="how">{e(a['howWeSpeak'])}</p><div class="kw">{kw}</div></div>
<div>{ex}</div></div>
<div class="say"><div class="do"><p>We say</p><ul>{say}</ul></div><div class="dont"><p>We don’t say</p><ul>{dont}</ul></div></div>
</article>'''

seg = ''.join(f'<button role="tab" aria-selected="{"true" if i==0 else "false"}" data-aud="{e(u["id"])}">{e(u["name"])}</button>' for i, u in enumerate(auds))
name = {u['id']: u['name'] for u in auds}
prom = ''.join(f'''<div class="prom"><p class="who">{e(name[p['audience']])}</p><p class="pl">{e(p['promise'])}</p>
<p class="exl">Perceptions we want to build</p><ul>{''.join(f"<li>{e(x)}</li>" for x in p['perceptions'])}</ul></div>''' for p in V['promises'])

sec = f'''<!-- VOICE:START (generated by build-voice.py from brand-story.json) -->
<section class="sec" id="voice" data-aud="{e(auds[0]['id'])}"><div class="wrap">
  <header class="sec-head"><span class="n">10.0</span><h2>Verbal Language</h2></header>
  <p class="draft"><b>Draft.</b> This chapter is proposed wording by OZ GLOBAL B2B, built on the Strategic Map. It is pending Galcon-Sentek approval.</p>

  <div class="sub">
    <div class="sub-head"><span class="n">10.1</span><h3>Brand Balance</h3></div>
    <p class="lede">{e(S['balance']['intro'])}</p>
    <div class="balance">
      {polecard(A,'pa')}
      <div class="axis" aria-hidden="true"><span></span><b>Growing <br>Wisely <br>Together</b><span></span></div>
      {polecard(B,'pb')}
    </div>
  </div>

  <div class="sub">
    <div class="sub-head"><span class="n">10.2</span><h3>Tone of Voice</h3></div>
    <p class="lede">{e(V['intro'])}</p>
    <div class="segbar"><span id="seg-l">Show examples for</span><div class="seg" role="tablist" aria-labelledby="seg-l">{seg}</div></div>
    {''.join(attr(a) for a in V['attributes'])}
  </div>

  <div class="sub">
    <div class="sub-head"><span class="n">10.3</span><h3>Promises &amp; Perceptions</h3></div>
    <p class="lede">{e(V['promisesIntro'])}</p>
    <div class="proms">{prom}</div>
  </div>
</div></section>
<!-- VOICE:END -->'''

h = open('index.html', encoding='utf-8').read()
if 'VOICE:START' in h:
    h = re.sub(r'<!-- VOICE:START.*?VOICE:END -->', lambda m: sec, h, flags=re.S)
else:
    h = h.replace('\n<footer>', '\n' + sec + '\n\n<footer>', 1)
open('index.html', 'w', encoding='utf-8').write(h)
print('voice chapter written')
